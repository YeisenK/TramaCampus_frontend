# ---------------------------------------------------------------------------
# Helper functions
# ---------------------------------------------------------------------------


def translate_label(item_id, label, translation_dict):
    """Return the Spanish label for item_id if present, otherwise keep label."""
    if translation_dict is None:
        return label
    return translation_dict.get(item_id, label)


def translate_standard_catalog(data, sets_dict, subsets_dict, items_dict):
    """Translate sets, their subsets, and items in a standard catalog."""
    for s in data.get("sets", []):
        s["label"] = translate_label(s["id"], s["label"], sets_dict)
        for sub in s.get("subsets", []):
            if subsets_dict is not None:
                sub["label"] = translate_label(sub["id"], sub["label"], subsets_dict)

    for item in data.get("items", []):
        item["label"] = translate_label(item["id"], item["label"], items_dict)


def translate_academic_catalog(data, areas_dict, items_dict):
    """Translate areas and items in the academic catalog."""
    for area in data.get("areas", []):
        area["label"] = translate_label(area["id"], area["label"], areas_dict)

    for item in data.get("items", []):
        item["label"] = translate_label(item["id"], item["label"], items_dict)


