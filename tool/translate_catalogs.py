# Main
# ---------------------------------------------------------------------------


def main():
    updated = []

    for filename, config in CATALOG_CONFIG.items():
        filepath = os.path.join(CATALOGS_DIR, filename)

        if not os.path.isfile(filepath):
            print(f"  SKIP  {filename} (file not found)")
            continue

        with open(filepath, "r", encoding="utf-8") as f:
            data = json.load(f)

        if config["type"] == "academic":
            translate_academic_catalog(
                data,
                areas_dict=config["areas_dict"],
                items_dict=config["items_dict"],
            )
        else:
            translate_standard_catalog(
                data,
                sets_dict=config["sets_dict"],
                subsets_dict=config["subsets_dict"],
                items_dict=config["items_dict"],
            )

        with open(filepath, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
            f.write("\n")

        print(f"  OK    {filename}")
        updated.append(filename)

    print(f"\nDone. Updated {len(updated)} file(s).")


if __name__ == "__main__":
    main()
